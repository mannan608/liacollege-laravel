  <script>
    (function() {
      const carousel = document.getElementById('first-aid-carousel');
      const items = carousel.querySelectorAll('[data-carousel-item]');
      const indicators = carousel.querySelectorAll('[data-carousel-slide-to]');
      const prevBtn = carousel.querySelector('[data-carousel-prev]');
      const nextBtn = carousel.querySelector('[data-carousel-next]');
      let currentIndex = 0;
      const total = items.length;

      function showSlide(index) {
        items.forEach((item, i) => {
          if (i === index) {
            item.classList.remove('hidden');
            item.setAttribute('data-carousel-item', 'active');
          } else {
            item.classList.add('hidden');
            item.removeAttribute('data-carousel-item');
            item.setAttribute('data-carousel-item', '');
          }
        });
        indicators.forEach((ind, i) => {
          if (i === index) {
            ind.setAttribute('aria-current', 'true');
            ind.classList.add('bg-white', 'text-red-600');
            ind.classList.remove('bg-red-600', 'text-white');
          } else {
            ind.setAttribute('aria-current', 'false');
            ind.classList.remove('bg-white', 'text-red-600');
            ind.classList.add('bg-red-600', 'text-white');
          }
        });
      }

      prevBtn.addEventListener('click', () => {
        currentIndex = (currentIndex - 1 + total) % total;
        showSlide(currentIndex);
      });

      nextBtn.addEventListener('click', () => {
        currentIndex = (currentIndex + 1) % total;
        showSlide(currentIndex);
      });

      indicators.forEach((ind, i) => {
        ind.addEventListener('click', () => {
          currentIndex = i;
          showSlide(currentIndex);
        });
      });

      // Initialize
      showSlide(0);
    })();
  </script>